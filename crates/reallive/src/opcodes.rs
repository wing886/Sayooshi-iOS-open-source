pub fn name(op: Opcode) -> Option<&'static str> {
    let module = match (op.modtype, op.module) {
        (0, 5 | 6) => 1,
        (_, module) => module,
    };
    NAMES
        .iter()
        .find(|(modtype, m, opcode, _)| {
            *modtype == op.modtype && *m == module && *opcode == op.opcode
        })
        .map(|entry| entry.3)
}
