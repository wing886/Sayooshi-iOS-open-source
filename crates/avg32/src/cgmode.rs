//! CG-mode catalogue (`MODE.CGM`).
//!
//! The file is an XOR-scrambled `PACK` stream of 36-byte records: a
//! 32-byte PDT name and the bit flag that records whether the player has
//! seen it.  Loading any listed PDT sets that flag.

