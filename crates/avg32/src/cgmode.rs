#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct CgEntry {
    pub name: String,
    pub flag: i32,
}

#[derive(Debug, Clone, Default)]
pub struct CgMode {
    pub entries: Vec<CgEntry>,
}

impl CgMode {
    pub fn parse(bytes: &[u8]) -> Result<Self> {
        if bytes.len() < 32 {
            bail!("avg32: MODE.CGM is shorter than its header");
        }
        let count = u32::from_le_bytes(bytes[16..20].try_into().expect("four bytes")) as usize;
        let body: Vec<u8> = bytes[32..]
            .iter()
            .enumerate()
            .map(|(index, byte)| byte ^ KEY[index & 255])
            .collect();
        if body.len() < 16 || &body[..4] != b"PACK" {
            bail!("avg32: MODE.CGM payload is not PACK-compressed");
        }
        let size = u32::from_le_bytes(body[8..12].try_into().expect("four bytes")) as usize;
        let table = unpack_lz(&body[16..], size).context("avg32: failed to unpack MODE.CGM")?;
        let mut entries = Vec::with_capacity(count);
        for record in table.chunks_exact(36).take(count) {
            let name_end = record[..32]
                .iter()
                .position(|byte| *byte == 0)
                .unwrap_or(32);
            entries.push(CgEntry {
                name: crate::nls::decode_name(&record[..name_end]),
                flag: i32::from_le_bytes(record[32..36].try_into().expect("four bytes")),
            });
        }
        Ok(Self { entries })
    }

    /// A PDT was shown.
    pub fn mark_seen(&self, name: &str, flags: &mut Flags) {
        if let Some(entry) = self
            .entries
            .iter()
            .find(|entry| entry.name.eq_ignore_ascii_case(name))
        {
            flags.set_bit(entry.flag, true);
        }
    }

    pub fn total(&self) -> i32 {
        self.entries.len() as i32
    }

    pub fn seen_count(&self, flags: &Flags) -> i32 {
        self.entries
            .iter()
            .filter(|entry| flags.bit(entry.flag))
            .count() as i32
    }

    pub fn percentage(&self, flags: &Flags) -> i32 {
        if self.entries.is_empty() {
            0
        } else {
            self.seen_count(flags) * 100 / self.total()
        }
    }

    pub fn seen(&self, index: i32, flags: &Flags) -> bool {
        self.entry(index).is_some_and(|entry| flags.bit(entry.flag))
    }

    pub fn entry(&self, index: i32) -> Option<&CgEntry> {
        usize::try_from(index)
            .ok()
            .and_then(|index| self.entries.get(index))
    }
}
